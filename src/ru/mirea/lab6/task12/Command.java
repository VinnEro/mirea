package ru.mirea.lab6.task12;

// Шаблон "Команда": каждое изменение строки оформляется как отдельный объект,
// который умеет и выполнить себя, и отменить. Тогда undo - это просто "взять последнюю команду и вызвать undo()",
// и UndoableStringBuilder не нужно знать подробностей каждой операции.
public interface Command {
    void execute();
    void undo();
}
